MUSIC = {"Music": "背景音乐"}


def slugify(value: str) -> str:
    value = re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")
    return value


TARGETS: dict[str, tuple[str, str, str]] = {}
for role, values in (
    ("sound_effect", SOUND_EFFECTS),
    ("ambience", AMBIENCE),
    ("music", MUSIC),
):
    for event_name, zh_label in values.items():
        TARGETS[event_name] = (slugify(event_name), zh_label, role)
